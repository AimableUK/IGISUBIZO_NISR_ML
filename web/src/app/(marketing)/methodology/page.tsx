export default function Methodology() {
  return (
    <Prose
      title="Methodology and data sources"
      intro="How Isesengura routes questions through statistical analysis code and reports whether each result uses generated proxy data or a published NISR table."
    >
      <h2>From question to result</h2>
      <ol className="mb-4 ml-5 list-decimal space-y-1">
        <li>The natural language question is routed to the right engine (decision/career, clustering, regression, or forecasting).</li>
        <li>The Python analysis service loads generated proxy CSVs (<code>model/data/real/</code>) and a public NISR crop-yield table (<code>model/data/official/</code>).</li>
        <li>Statistical and decision-rule code computes a result. Each result identifies its source and whether its input is demo data.</li>
        <li>A deterministic rule-based planner maps the result to a <code>PresentationSpec</code> (charts/tables/maps/metrics/insights). The layout never changes the numbers.</li>
        <li>Everything is saved as an artifact (question, result, sources, spec, versions) and can be reopened unchanged.</li>
      </ol>

      <h2>Engines</h2>
      <ul>
        <li>
          <strong>Career and study decisions.</strong> Compares named study programs with enrollment, graduation, graduate-employment, and wage indicators, and maps applied-mathematics skills to potential sectors, occupations, and locations. These education and job-demand inputs are generated demo proxies, not verified evidence of employer requirements or entry-level hiring.
        </li>
        <li>
          <strong>General dataset questions.</strong> Matches supported measures in 12 CSV datasets and can summarize a topic, compare or rank districts/categories, filter named locations, and show historical trends when the requested years are available. Crop-yield questions use a published NISR table.
        </li>
        <li>
          <strong>Problem A — District labour underutilization (clustering).</strong> K-means (k=3) on normalized features: underemployment, unemployment, youth NEET, agriculture share, formal employment share, and secondary+ education share. Produces district clusters and profiles.
        </li>
        <li>
          <strong>Problem B — Youth NEET predictors (regression).</strong> Panel OLS on district×year observations with year fixed effects, ridge stabilization, and leave-one-district-out cross-validation. Reports coefficients, R²/adjusted R², Q²/RMSE, and feature importance. Coefficients show association, not causation; n is small.
        </li>
        <li>
          <strong>Problem C — Sector employment trends &amp; forecast (forecasting).</strong> Linear trend per sector with 95% prediction intervals; backtested on held-out years.
        </li>
        <li>
          <strong>Decision / Career.</strong> Demonstrates weighted comparisons using generated proxy indicators. The system ranks options; it never makes the final decision. Do not use demo rankings for real decisions.
        </li>
      </ul>

      <h2>Data sources</h2>
      <p>
        The proxy datasets use categories modeled on NISR Labour Force Survey, EICV7, DHS, Seasonal Agricultural Survey, EMIS/REB, NESA, Establishment Census, WDA/HEC, and LMIS/KORA. They are generated by repository scripts and have not been verified against official source tables. Crop-yield results instead use NISR&apos;s public{" "}
        <a href="https://pxweb.statistics.gov.rw/pxweb/en/NISR%20Statistical%20Databases/Agriculture/Crop%20area,%20production%20and%20yield%20for%20major%20crops/yield.px">district and crop yield table</a>. It includes Season A/B observations but does not state a reference year. See <code>model/README.md</code> for details.
      </p>

      <h2>Limits &amp; principles</h2>
      <ul>
        <li><strong>Demo and missing data:</strong> Generated proxies are not official statistics; the NISR crop-yield table is separately cited, missing observations are omitted rather than treated as zero, and its reference year is not stated.</li>
        <li><strong>Transparency:</strong> Every result lists sources, operations, caveats, and versions.</li>
        <li><strong>Separation of concerns:</strong> Models compute numbers; the LLM (if used) only plans layout/explains — never generates statistics.</li>
        <li><strong>Reproducibility:</strong> Analytical results are immutable; presentation customizations are versioned separately.</li>
      </ul>
    </Prose>
  );
}
